Battery Charge Alert – App Description

Battery Charge Alert is a simple and useful Flutter application that helps users avoid unnecessary overcharging by notifying them when their phone reaches a user-defined battery level.

The app allows users to choose any battery percentage between 1% and 100%. Once the phone is connected to a charger, the app continuously monitors the battery level in the background. When the battery reaches the selected percentage (for example, 90%), it immediately plays a loud alarm and vibrates the device, reminding the user to unplug the charger.

The application is designed to make charging more convenient while encouraging good charging habits that may help reduce the amount of time a battery spends at very high charge levels.

Key Features

- Select any battery level from 1% to 100% for the charging alert.
- Real-time battery percentage and charging status.
- Loud alarm when the selected battery level is reached.
- Optional vibration with the alarm.
- User-configurable alarm duration (e.g., 15 seconds, 30 seconds, 1 minute, 2 minutes, 5 minutes, or until manually stopped, depending on device capabilities).
- Works while the phone is charging, even when the app is running in the background (using an Android foreground service).
- Automatically saves the user's preferred battery alert percentage.
- Support for custom alarm sounds.
- Simple, lightweight, and user-friendly interface.
- Optional dark mode support.

Future Enhancements

- Battery full (100%) alert mode.
- Charging history and statistics.
- Estimated remaining charging time.
- Battery temperature monitoring and overheating alerts.
- Battery health tips and charging recommendations.
- Automatic start after device reboot.
- Home screen widget and Quick Settings tile.
- Smart charging schedules and Do Not Disturb support.
- Wearable device notifications.

Objective

The primary objective of the application is to provide users with a reliable charging reminder that helps prevent them from forgetting their phone on charge for long periods. By playing a customizable alarm when the selected battery level is reached, the app offers a simple, reliable, and convenient charging experience.
